function ADVANCED_ATTRIBUTES:onEquip(player, item)
    local attributes = ADVANCED_ATTRIBUTES:getAttributes(item)
	if attributes then
	    local _sendSkills = false
		local _sendStats = false
	    for i, v in pairs(attributes) do
		    local attributeTable = self.attributeTable[v.id]
			if attributeTable then
			    local attributeType = attributeTable.type
				local id = i
				if attributeTable.id then
				    id = attributeTable.id
				end
				
				if attributeType ~= ADVANCED_ATTRIBUTE_TYPE_ITEM then
				    player:addAdvancedAttribute(attributeType, id, v.value)
				end
				
				if attributeTable._saveStatus then
				    player:addAdvancedAttribute(ADVANCED_ATTRIBUTE_TYPE_PLAYER_EFFECTS, ADVANCED_ATTRIBUTE_PLAYER_STATUS_STORE, i)
				end
		    
				if attributeType == ADVANCED_ATTRIBUTE_TYPE_SKILL and not _sendSkills then
			        _sendSkills = true
			    end
				
				if attributeType == ADVANCED_ATTRIBUTE_TYPE_STATS and not _sendStats then
			        _sendStats = true
			    end
				
				if i == ADVANCED_ATTRIBUTE_ITEM_SPEED then
				    player:changeSpeed(v.value * 2)
				end
			end
		end
		
		if _sendSkills then
		    player:sendSkills()
		end
		if _sendStats then
		    player:sendStats()
		end
	end
	return true
end

