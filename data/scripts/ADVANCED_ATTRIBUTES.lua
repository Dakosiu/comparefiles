function ADVANCED_ATTRIBUTES:getAttributeByString(attributeString)
    return tonumber(self.stringTable[attributeString])
end

function ADVANCED_ATTRIBUTES:getAttributeDescription(attribute, value)
    local t = self:getAttributeTable(attribute)
	if not t or t.hide then
	    return false
	end
	local str = t.name
	local prefix = "+"
	if t._negative then
	    prefix = "-"
	end

	str = str .. " " .. prefix .. value
		
	if t._percentage then
	    str = str .. '%%'
	end	
    return str
end

function ADVANCED_ATTRIBUTES:isHideFromDescription(attribute)
    return self.attributeTable[attribute].hide
end

function ADVANCED_ATTRIBUTES:getClasificationTable(attribute, classification)
    local t = CLASSIFICATION_ITEM_LIST[attribute]
	if not t then
	    return nil
	end
    local value = t[classification]
	return value
end

function ADVANCED_ATTRIBUTES:getFactorTable()
    return CLASSIFICATION_FACTOR
end

function ADVANCED_ATTRIBUTES:getAttributeTable(attribute)
    return self.attributeTable[attribute]
end

local keys = {
                STORE_ATTRIBUTES = "ADVANCED_ATTRIBUTES_STORE"
			 }

function ADVANCED_ATTRIBUTES:storeAttribute(item, advancedAttribute, value)
	local attributes = item:getCustomAttribute(keys.STORE_ATTRIBUTES)
	if attributes then
	    attributes = json.decode(attributes)
	else
	    attributes = {}
	end
	attributes["attr" .. advancedAttribute] =  { value = value, id = advancedAttribute } 
	item:setCustomAttribute(keys.STORE_ATTRIBUTES, json.encode(attributes))
end

function ADVANCED_ATTRIBUTES:getAttributes(item)
    if not item then
	    return nil
	end
    local attributes = item:getCustomAttribute(keys.STORE_ATTRIBUTES)
	if not attributes then
	    return nil
	end
	
	attributes = json.decode(attributes)
	return attributes
end

local errorList = {}
function ADVANCED_ATTRIBUTES:addAttribute(item, attribute, classification, customAmount, customChance)
    if not attribute then
	    print(">> [ADVANCED_ATTRIBUTES]" .. " Attribute ENUM MISSING")
		return false
	end
		
    local classificationTable = self:getClasificationTable(attribute, classification)
	if not classificationTable then
	    if not errorList[attribute] then
	       print(">> [ADVANCED_ATTRIBUTES]" .. " Error on id: " .. attribute)
		   errorList[attribute] = true
		end
		return false
	end
	
	
	local attributeTable = self:getAttributeTable(attribute)
	local amount = classificationTable.VALUE_AMOUNT
	if amount then
	    if customAmount then
		    amount = customAmount
		end
        item:setAdvancedAttribute(attribute, amount)
		self:storeAttribute(item, attribute, amount)
	end
	local secondary = attributeTable.secondaryAttribute
	if secondary then
	    local chance = classificationTable.VALUE_CHANCE
		if chance then
		    if customChance then
			    chance = customChance
			end
		    item:setAdvancedAttribute(secondary, chance)
			--self:storeAttribute(item, secondary, chance)
		end
	end	
	item:setAdvancedAttribute(ADVANCED_ATTRIBUTE_ITEM_BONUS_COUNT, item:getAdvancedAttribute(ADVANCED_ATTRIBUTE_ITEM_BONUS_COUNT) + 1)
end

