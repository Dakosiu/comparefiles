function ADVANCED_ATTRIBUTES:rollBonuses(item, bonusCount)
    local name = item:getName():lower()
	local itemTable = ATTRIBUTES_ITEM_LIST[name]
	if not itemTable then
	    return false
	end
	local itemType = ItemType(name)
	local classification = itemType:getClassification()
	if classification == 0 then
	    return false
	end
	if classification < bonusCount then
	    print(">> [ERROR] - ADVANCED_ATTRIBUTES_SYSTEM: Bonus Count its higher than item classification.")
		return false
	end
		
	local cl = classification	
	local avaibleAttributes = {}
	
	local rolledBonuses = {}
	local rolledArray = {}
	while cl >= 1 do
	    for i, v in ipairs(itemTable) do
		    local attributeId = v
		    if type(attributeId) == "string" then
			    attributeId = ADVANCED_ATTRIBUTES:getAttributeByString(v)
			end
			local classificationTable = self:getClasificationTable(attributeId, cl)
			local values = {}
			values.ID = attributeId
			values.CLASSIFICATION = cl
			values.ROLL_CHANCE = classificationTable.ROLL_CHANCE
			table.insert(avaibleAttributes, values)
	    end
	    cl = cl - 1
	end
	
	table.sort(avaibleAttributes, function(a, b) return a.ROLL_CHANCE < b.ROLL_CHANCE end)
	
	
	for i = 1, bonusCount do
        local rand = math.random(1, 100)
	    for i, v in ipairs(avaibleAttributes) do
	        local chance = v.ROLL_CHANCE * 100
		    if rand <= chance and not rolledArray[v] then
		        table.insert(rolledBonuses, v)
			    rolledArray[v] = v
		    end
		end
	end
	
	if #rolledBonuses == 0 then
	    return
	end
	
	local bonusUsed = {}
	for i = 1, bonusCount do
	    local index = math.random(1, #rolledBonuses)
	    local bonus = rolledBonuses[index]
	    while bonusUsed[bonus] do
		    rolledBonuses[index] = nil
		    index = math.random(1, #rolledBonuses)
			bonus = rolledBonuses[index]
		end
		if bonus then
		   bonusUsed[bonus] = true
		   ADVANCED_ATTRIBUTES:addAttribute(item, tonumber(bonus.ID), bonus.CLASSIFICATION)
		   	print("Wylosowany Bonus: " .. "ID: " .. bonus.ID .. " CLASIFICATION:" .. bonus.CLASSIFICATION)
		end
	end
		
	
end	
	
	
	
	
	
	


