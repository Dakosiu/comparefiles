function ADVANCED_ATTRIBUTES:generateTestItem(player, itemid, classification, allAttributes, customAmount, customChance)
	local item = player:addItem(itemid, 1)
	if not item then
	    return
	end
	
	local name = item:getName():lower()
	local itemTable = ATTRIBUTES_ITEM_LIST[name]
	if not itemTable then
	   print("<< [ADVANCED_ATTRIBUTES] - Warning:  " .. "ItemID: " .. itemid .. " " .. "Name: " .. name .. " not found in attributes table.")
	   return false
	end
	
	if allAttributes then
	    for i, v in ipairs(itemTable) do
		    local attributeId = v
		    if type(attributeId) == "string" then
			    attributeId = ADVANCED_ATTRIBUTES:getAttributeByString(v)
			end
			if not attributeId then
			    print("<< [ADVANCED_ATTRIBUTES] - Warning:" .. "Attribute Name: " .. v .. " not implemented.")
			else
			    self:addAttribute(item, attributeId, classification, customAmount, customChance)
			end			
		end
	end
end
	    
	

